CREATE TABLE ai_invocation (
    id                   VARCHAR(64) PRIMARY KEY,
    cycle_id             VARCHAR(64),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    model                VARCHAR(200),
    model_version        VARCHAR(200),
    system_prompt        TEXT,
    user_prompt          TEXT,
    request_payload      TEXT,
    parameters           TEXT,
    metrics_context      TEXT,
    history_context      TEXT,
    raw_response         TEXT,
    decision             VARCHAR(32),
    proposed_admission   INTEGER,
    proposed_max_queue   INTEGER,
    rationale            TEXT,
    validation_status    VARCHAR(32) NOT NULL,
    validation_errors    TEXT,
    evaluation           TEXT,
    outcome              VARCHAR(64),
    policy_version_before INTEGER,
    candidate_version    INTEGER,
    duration_ms          BIGINT NOT NULL,
    prompt_tokens        INTEGER,
    completion_tokens    INTEGER,
    status               VARCHAR(16) NOT NULL,
    error                TEXT,
    redacted             BOOLEAN NOT NULL
);
CREATE INDEX idx_ai_invocation_created ON ai_invocation (created_at DESC);
CREATE INDEX idx_ai_invocation_cycle ON ai_invocation (cycle_id);

CREATE TABLE evolution_event (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time        TIMESTAMP WITH TIME ZONE NOT NULL,
    level             VARCHAR(8) NOT NULL,
    component         VARCHAR(64) NOT NULL,
    stage             VARCHAR(32) NOT NULL,
    cycle_id          VARCHAR(64),
    ai_invocation_id  VARCHAR(64),
    policy_version    INTEGER,
    message           TEXT NOT NULL,
    data              TEXT
);
CREATE INDEX idx_evolution_event_time ON evolution_event (event_time DESC);
CREATE INDEX idx_evolution_event_cycle ON evolution_event (cycle_id);
